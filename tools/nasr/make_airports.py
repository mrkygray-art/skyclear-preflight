# Builds src/airports_nasr.js from the FAA NASR 28-day subscription (CSV edition).
# Source: https://nfdc.faa.gov/webContent/28DaySub/extra/<DD_Mon_YYYY>_CSV.zip  (official FAA data)
# Usage:  python -I tools/nasr/make_airports.py <NASR_CSV.zip> src/airports_nasr.js
# Rerun every 28-day cycle (the effective date is written into the output and shown in the app).
import csv
import io
import json
import sys
import zipfile

ZIP, OUT = sys.argv[1], sys.argv[2]
z = zipfile.ZipFile(ZIP)


def rd(name):
    return list(csv.DictReader(io.TextIOWrapper(z.open(name), encoding="latin-1")))


# Coverage: SkyClear's chart layers (LA, SF, Las Vegas, Phoenix sectionals and the San Diego TAC), with a small margin.
LAT0, LAT1, LON0, LON1 = 31.2, 40.25, -125.2, -108.6

base = [r for r in rd("APT_BASE.csv")
        if r["SITE_TYPE_CODE"] == "A" and r["FACILITY_USE_CODE"] == "PU" and r["ARPT_STATUS"] == "O"
        and LAT0 <= float(r["LAT_DECIMAL"]) <= LAT1 and LON0 <= float(r["LONG_DECIMAL"]) <= LON1]
ids = {r["ARPT_ID"] for r in base}
eff = base[0]["EFF_DATE"].replace("/", "-")

cls = {r["ARPT_ID"]: r for r in rd("CLS_ARSP.csv") if r["ARPT_ID"] in ids}
awos = {}
for r in rd("AWOS.csv"):
    if r["ASOS_AWOS_ID"] in ids:
        awos.setdefault(r["ASOS_AWOS_ID"], r["ASOS_AWOS_TYPE"])

frq = {}
for r in rd("FRQ.csv"):
    a = r["SERVICED_FACILITY"]
    if a in ids:
        frq.setdefault(a, []).append(r)


def vhf(f):
    try:
        v = float(f.split("/")[0])
        return 108 <= v < 137
    except ValueError:
        return False


def uniq(seq):
    out = []
    for x in seq:
        if x and x not in out:
            out.append(x)
    return out


def hours(h):
    h = (h or "").strip()
    return "Continuous" if h in ("24", "0000-2359") else h


apts = []
for r in base:
    a = r["ARPT_ID"]
    rows = frq.get(a, [])
    atct = [x for x in rows if x["FACILITY_TYPE"].startswith("ATCT")]
    use = lambda pre, src=atct: uniq([x["FREQ"] for x in src if x["FREQ_USE"].upper().startswith(pre) and vhf(x["FREQ"])])
    twr = use("LCL")
    gnd = use("GND")
    cd = use("CD")
    atis = uniq([x["FREQ"] for x in atct if x["FREQ_USE"].upper() in ("ATIS", "D-ATIS") and vhf(x["FREQ"])])
    ctaf = uniq([x["FREQ"] for x in rows if x["FREQ_USE"].upper() == "CTAF" and vhf(x["FREQ"])])
    unicom = uniq([x["FREQ"] for x in rows if x["FREQ_USE"].upper() == "UNICOM" and vhf(x["FREQ"])])
    wxf = uniq([x["FREQ"] for x in rows if x["FACILITY_TYPE"] == "ASOS_AWOS" and vhf(x["FREQ"])])
    appr = [x for x in rows if x["FACILITY_TYPE"] in ("TRACON", "RAPCON", "ARTCC", "RCAG") and "APCH" in x["FREQ_USE"].upper() and vhf(x["FREQ"])]
    app = uniq([x["FREQ"] for x in appr])[:4]
    app_name = next((x["PRIMARY_APPROACH_RADIO_CALL"] for x in appr if x["PRIMARY_APPROACH_RADIO_CALL"]), "")
    twr_hrs = next((hours(x["TOWER_HRS"]) for x in atct if x["TOWER_HRS"]), "")
    c = cls.get(a, {})
    k = "B" if c.get("CLASS_B_AIRSPACE") == "Y" else "C" if c.get("CLASS_C_AIRSPACE") == "Y" else "D" if c.get("CLASS_D_AIRSPACE") == "Y" else None
    o = {"id": a, "icao": r["ICAO_ID"] or None, "name": r["ARPT_NAME"].title(), "city": r["CITY"].title(), "st": r["STATE_CODE"],
         "lat": round(float(r["LAT_DECIMAL"]), 5), "lon": round(float(r["LONG_DECIMAL"]), 5),
         "elev": round(float(r["ELEV"])) if r["ELEV"] else None, "cls": k}
    if c.get("CLASS_E_AIRSPACE") == "Y" and not k:
        o["clsE"] = True
    if c.get("AIRSPACE_HRS"):
        o["clsHrs"] = c["AIRSPACE_HRS"]
    if twr:
        o["twr"] = " · ".join(twr)
        o["hrs"] = twr_hrs or "not listed"
    if gnd:
        o["gnd"] = " · ".join(gnd)
    if cd:
        o["cd"] = " · ".join(cd)
    if atis:
        o["atis"] = " · ".join(atis)
    if app:
        o["app"] = ((app_name.title() + ": ") if app_name else "") + " · ".join(app)
    if ctaf:
        o["ctaf"] = " · ".join(ctaf)
    if unicom:
        o["unicom"] = " · ".join(unicom)
    if a in awos:
        o["wx"] = awos[a] + (" " + " · ".join(wxf) if wxf else "")
    apts.append(o)

apts.sort(key=lambda o: o["id"])
js = ("/* GENERATED by tools/nasr/make_airports.py from the FAA NASR CSV edition effective " + eff +
      ". Do not hand-edit. Public-use airports in SkyClear's chart coverage. */\n"
      "const NASR_EFF=" + json.dumps(eff) + ";\n"
      "const AIRPORTS_NASR=" + json.dumps(apts, separators=(",", ":")) + ";\n")
open(OUT, "w", encoding="utf-8").write(js)
print(len(apts), "airports;", sum(1 for o in apts if o.get("twr")), "towered;", sum(1 for o in apts if o.get("wx")), "with ASOS/AWOS;", len(js) // 1024, "KB; effective", eff)
